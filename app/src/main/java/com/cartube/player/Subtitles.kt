package com.cartube.player

import androidx.media3.common.C
import androidx.media3.common.Format
import androidx.media3.common.MediaItem
import androidx.media3.common.MimeTypes
import androidx.media3.datasource.DataSource
import androidx.media3.exoplayer.source.MediaSource
import androidx.media3.exoplayer.source.ProgressiveMediaSource
import androidx.media3.extractor.ExtractorsFactory
import androidx.media3.extractor.text.DefaultSubtitleParserFactory
import androidx.media3.extractor.text.SubtitleExtractor
import androidx.media3.extractor.text.SubtitleParser
import androidx.media3.extractor.text.CuesWithTiming
import androidx.media3.common.text.Cue
import androidx.media3.common.util.Consumer
import android.text.Layout
import com.cartube.data.Settings
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.SubtitlesStream
import java.util.Locale

/**
 * Side-loaded subtitle tracks for a YouTube video.
 *
 * Swedish is always offered when the video has any captions: a real Swedish track if there
 * is one, otherwise YouTube's machine translation of the original captions (the `tlang`
 * parameter of its caption URLs). The original-language track is offered too, so the
 * viewer can switch with the CC button.
 */
object Subtitles {
    private const val TARGET = "sv"
    private val swedish = Locale("sv")
    private val parserFactory = DefaultSubtitleParserFactory()

    fun sources(info: StreamInfo, data: DataSource.Factory): List<MediaSource> {
        val tracks = info.subtitles.filter { it.isUrl && it.content.isNotBlank() }
        if (tracks.isEmpty()) return emptyList()
        val mode = Settings.subtitles

        val nativeSwedish = tracks
            .filter { it.languageTag.lowercase().startsWith(TARGET) }
            .minByOrNull { if (it.isAutoGenerated) 1 else 0 }
        // Captions written by the uploader translate far better than speech recognition.
        val original = tracks.firstOrNull { !it.isAutoGenerated } ?: tracks.first()

        val result = mutableListOf<MediaSource>()
        if (nativeSwedish != null) {
            result += source(
                url = nativeSwedish.content,
                language = TARGET,
                label = label(nativeSwedish),
                isDefault = mode == Settings.SUBTITLES_SWEDISH,
                data = data,
            )
        } else {
            result += source(
                url = withParam(original.content, "tlang", TARGET),
                language = TARGET,
                label = "Svenska (översatt)",
                isDefault = mode == Settings.SUBTITLES_SWEDISH,
                data = data,
            )
        }
        if (original !== nativeSwedish) {
            result += source(
                url = original.content,
                language = original.languageTag,
                label = label(original),
                isDefault = mode == Settings.SUBTITLES_ORIGINAL,
                data = data,
            )
        }
        return result
    }

    private fun label(track: SubtitlesStream): String {
        val name = Locale.forLanguageTag(track.languageTag).getDisplayLanguage(swedish)
            .replaceFirstChar { it.titlecase(swedish) }
            .ifBlank { track.languageTag }
        return if (track.isAutoGenerated) "$name (automatisk)" else name
    }

    /** Replaces or adds a query parameter on a YouTube caption URL. */
    private fun withParam(url: String, key: String, value: String): String =
        url.replace(Regex("&$key=[^&]*"), "") + "&$key=$value"

    private fun source(
        url: String,
        language: String,
        label: String,
        isDefault: Boolean,
        data: DataSource.Factory,
    ): MediaSource {
        // WebVTT is the caption format ExoPlayer handles best, so ask YouTube for that.
        val vttUrl = withParam(url, "fmt", "vtt")
        val format = Format.Builder()
            .setId("$language:$label")
            .setSampleMimeType(MimeTypes.TEXT_VTT)
            .setLanguage(language)
            .setLabel(label)
            .setSelectionFlags(if (isDefault) C.SELECTION_FLAG_DEFAULT else 0)
            .build()
        // Parse while loading, the way ExoPlayer itself handles side-loaded subtitles.
        val parser = CenteredParser(parserFactory.create(format))
        val extractors = ExtractorsFactory { arrayOf(SubtitleExtractor(parser, format)) }
        return ProgressiveMediaSource.Factory(data, extractors)
            .createMediaSource(MediaItem.fromUri(vttUrl))
    }

    /**
     * YouTube's caption files position each line for its own player (often flush left).
     * Drop that so every line is centred at the bottom of the video.
     */
    private class CenteredParser(private val delegate: SubtitleParser) : SubtitleParser {
        override fun parse(
            data: ByteArray,
            offset: Int,
            length: Int,
            outputOptions: SubtitleParser.OutputOptions,
            output: Consumer<CuesWithTiming>,
        ) {
            delegate.parse(data, offset, length, outputOptions) { cues ->
                output.accept(CuesWithTiming(cues.cues.map(::center), cues.startTimeUs, cues.durationUs))
            }
        }

        override fun getCueReplacementBehavior(): Int = delegate.cueReplacementBehavior

        override fun reset() = delegate.reset()

        private fun center(cue: Cue): Cue = cue.buildUpon()
            .setTextAlignment(Layout.Alignment.ALIGN_CENTER)
            .setPosition(Cue.DIMEN_UNSET)
            .setPositionAnchor(Cue.TYPE_UNSET)
            .setLine(Cue.DIMEN_UNSET, Cue.TYPE_UNSET)
            .setLineAnchor(Cue.TYPE_UNSET)
            .setSize(Cue.DIMEN_UNSET)
            .build()
    }
}
